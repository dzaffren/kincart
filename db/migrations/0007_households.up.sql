CREATE TABLE IF NOT EXISTS households (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rose_hash text UNIQUE,
  sam_hash text UNIQUE,
  started_at timestamptz NOT NULL DEFAULT now()
);

